export type BlockKind = "print" | "let" | "input" | "get" | "if" | "repeat" | "add" | "true" | "false" | "compare";
export type ValueType = "number" | "string" | "boolean";
export type Branch = { id: string; condition: string; children: Block[] };
export type Block = {
  id: string; kind: BlockKind; value: string; name?: string; right?: string; valueBlock?: Block; rightBlock?: Block;
  operator?: "+" | "-" | "*" | "/"; comparisonOperator?: "==" | ">=" | "<="; types?: ValueType[]; children?: Block[]; conditionBlock?: Block;
  elseIf?: Branch[]; elseChildren?: Block[]; elseId?: string;
};
export type Compilation = { code: string; errors: string[] };
export type RunResult = { output: string; error?: string };
const identifier = /^[A-Za-z_][A-Za-z0-9_]*$/;
const reserved = new Set(["print", "let", "input", "get", "if", "repeat", "true", "false", "else", "boolean", "compare"]);

function selectedLiteralType(block: Block): ValueType {
  const types = block.types?.length ? block.types : ["number"];
  if (types.includes("number")) return "number";
  if (types.includes("string")) return "string";
  if (types.includes("boolean")) return "boolean";
  return "number";
}
function literalForLanguage(block: Block): string {
  const type = selectedLiteralType(block);
  if (type === "string") return JSON.stringify(block.value);
  if (type === "boolean") return block.value.trim() === "true" ? "true" : "false";
  return block.value.trim() !== "" && Number.isFinite(Number(block.value)) ? String(Number(block.value)) : "0";
}
function literalForRuntime(block: Block): Value {
  const type = selectedLiteralType(block);
  if (type === "string") return block.value;
  if (type === "boolean") return block.value.trim() === "true";
  const value = Number(block.value);
  if (block.value.trim() === "" || !Number.isFinite(value)) throw new Error(`Variable "${block.name ?? "value"}" needs a numeric literal.`);
  return value;
}
function literalForC(block: Block): string {
  const type = selectedLiteralType(block);
  if (type === "string") return JSON.stringify(block.value);
  if (type === "boolean") return block.value.trim() === "true" ? "1" : "0";
  const value = Number(block.value);
  if (block.value.trim() === "" || !Number.isFinite(value)) throw new Error(`Variable "${block.name ?? "value"}" needs a numeric literal.`);
  return String(value);
}
function blockExpression(block: Block): string {
  if (block.kind === "true") return "true";
  if (block.kind === "false") return "false";
  if (block.kind === "get") return block.value || "value";
  if (block.kind === "add") return "(" + (block.valueBlock ? blockExpression(block.valueBlock) : block.value || "0") + ") " + (block.operator ?? "+") + " (" + (block.rightBlock ? blockExpression(block.rightBlock) : block.right || "1") + ")";
  if (block.kind === "compare") return "(" + (block.valueBlock ? blockExpression(block.valueBlock) : block.value || "0") + ") " + (block.comparisonOperator ?? "==") + " (" + (block.rightBlock ? blockExpression(block.rightBlock) : block.right || "0") + ")";
  throw new Error("This block cannot be used as a value.");
}
function conditionExpression(block: Block): string {
  if (block.kind === "true" || block.kind === "false" || block.kind === "compare") return blockExpression(block);
  throw new Error("An if condition needs a true/false or comparison block.");
}
function evaluateBlockValue(block: Block, variables: Map<string, Value>): Value {
  if (block.kind === "true") return true;
  if (block.kind === "false") return false;
  if (block.kind === "get") {
    const name = block.value.trim();
    if (!variables.has(name)) throw new Error(`Unknown variable "${name}".`);
    return variables.get(name)!;
  }
  if (block.kind === "add") {
    const left = block.valueBlock ? evaluateBlockValue(block.valueBlock, variables) : evaluate(block.value || "0", variables);
    const right = block.rightBlock ? evaluateBlockValue(block.rightBlock, variables) : evaluate(block.right || "1", variables);
    return numeric(left, right, block.operator ?? "+");
  }
  if (block.kind === "compare") {
    const left = block.valueBlock ? evaluateBlockValue(block.valueBlock, variables) : evaluate(block.value || "0", variables);
    const right = block.rightBlock ? evaluateBlockValue(block.rightBlock, variables) : evaluate(block.right || "0", variables);
    switch (block.comparisonOperator ?? "==") {
      case "==": return left === right;
      case ">=": return comparable(left, right, ">=", true, true);
      case "<=": return comparable(left, right, "<=", true);
    }
  }
  throw new Error("This block cannot be used as a value.");
}

export function compile(blocks: Block[]): Compilation {
  const errors: string[] = [];
  const lines: string[] = ["// Generated by Blorrl Studio", ""];
  function emit(items: Block[], depth: number) {
    const pad = "  ".repeat(depth);
    for (const [index, block] of items.entries()) {
      const line = index + 1;
      switch (block.kind) {
        case "print": lines.push(pad + "print " + (block.valueBlock ? blockExpression(block.valueBlock) : JSON.stringify(block.value)) + ";"); break;
        case "let": {
          const name = block.name?.trim() ?? "";
          if (!identifier.test(name) || reserved.has(name)) errors.push("Block " + line + ": invalid variable name \"" + name + "\".");
          else lines.push(pad + "let " + name + " = " + (block.valueBlock ? blockExpression(block.valueBlock) : literalForLanguage(block)) + ";");
          break;
        }
        case "input": {
          const name = block.name?.trim() ?? "";
          if (!identifier.test(name) || reserved.has(name)) errors.push("Block " + line + ": invalid input variable name \"" + name + "\".");
          else lines.push(pad + "let " + name + " = input();");
          break;
        }
        case "get": lines.push(pad + "print " + (block.value || "value") + ";"); break;
        case "true": lines.push(pad + "print true;"); break;
        case "false": lines.push(pad + "print false;"); break;
        case "compare": lines.push(pad + "print " + blockExpression(block) + ";"); break;
        case "if":
          lines.push(pad + "if (" + (block.conditionBlock ? conditionExpression(block.conditionBlock) : "false") + ") {");
          emit(block.children ?? [], depth + 1); lines.push(pad + "}");
          for (const branch of block.elseIf ?? []) {
            lines.push(pad + "else if (" + (branch.condition || "false") + ") {");
            emit(branch.children, depth + 1); lines.push(pad + "}");
          }
          if (block.elseChildren) { lines.push(pad + "else {"); emit(block.elseChildren, depth + 1); lines.push(pad + "}"); }
          break;
        case "repeat":
          lines.push(pad + "repeat (" + (block.valueBlock ? blockExpression(block.valueBlock) : block.value || "1") + ") {");
          emit(block.children ?? [], depth + 1); lines.push(pad + "}"); break;
        case "add": lines.push(pad + "print " + blockExpression(block) + ";"); break;
      }
    }
  }
  emit(blocks, 0);
  return { code: lines.join("\n"), errors };
}

type Token = { kind: "number" | "string" | "identifier" | "operator" | "eof"; value: string };
function tokenize(source: string): Token[] {
  const tokens: Token[] = [];
  let i = 0;
  while (i < source.length) {
    const ch = source[i]!;
    if (/\s/.test(ch)) { i++; continue; }
    if (ch === '"' || ch === "'") {
      const quote = ch; let value = ""; i++;
      while (i < source.length && source[i] !== quote) {
        if (source[i] === "\\" && i + 1 < source.length) {
          i++; const escaped = source[i]!;
          value += escaped === "n" ? "\n" : escaped === "t" ? "\t" : escaped;
        } else value += source[i];
        i++;
      }
      if (source[i] !== quote) throw new Error("Unterminated string literal.");
      i++; tokens.push({ kind: "string", value }); continue;
    }
    const number = source.slice(i).match(/^(?:\d+\.\d+|\d+|\.\d+)/);
    if (number) { tokens.push({ kind: "number", value: number[0] }); i += number[0].length; continue; }
    const name = source.slice(i).match(/^[A-Za-z_][A-Za-z0-9_]*/);
    if (name) { tokens.push({ kind: "identifier", value: name[0] }); i += name[0].length; continue; }
    const operator = ["==", "!=", "<=", ">=", "&&", "||", "+", "-", "*", "/", "%", "<", ">", "!", "(", ")"].find(op => source.startsWith(op, i));
    if (operator) { tokens.push({ kind: "operator", value: operator }); i += operator.length; continue; }
    throw new Error(`Unexpected character "${ch}" in expression.`);
  }
  tokens.push({ kind: "eof", value: "" });
  return tokens;
}

type Value = number | string | boolean;
const precedence: Record<string, number> = { "||": 1, "&&": 2, "==": 3, "!=": 3, "<": 4, "<=": 4, ">": 4, ">=": 4, "+": 5, "-": 5, "*": 6, "/": 6, "%": 6 };

function evaluate(expression: string, variables: Map<string, Value>): Value {
  const tokens = tokenize(expression);
  let position = 0;
  const peek = () => tokens[position]!;
  const take = () => tokens[position++]!;
  function primary(): Value {
    const token = take();
    if (token.kind === "number") return Number(token.value);
    if (token.kind === "string") return token.value;
    if (token.kind === "identifier") {
      if (token.value === "true") return true;
      if (token.value === "false") return false;
      if (!variables.has(token.value)) throw new Error(`Unknown variable "${token.value}".`);
      return variables.get(token.value)!;
    }
    if (token.value === "(") {
      const result = parse(0);
      if (take().value !== ")") throw new Error('Expected ")".');
      return result;
    }
    if (token.value === "!" || token.value === "-" || token.value === "+") {
      const value = primary();
      if (token.value === "!") return !value;
      if (typeof value !== "number") throw new Error(`Unary ${token.value} expects a number.`);
      return token.value === "-" ? -value : value;
    }
    throw new Error(`Expected a value, got "${token.value || "end of expression"}".`);
  }
  function parse(minPrecedence: number): Value {
    let left = primary();
    while (peek().kind === "operator" && (precedence[peek().value] ?? -1) >= minPrecedence) {
      const op = take().value;
      const right = parse((precedence[op] ?? 0) + 1);
      switch (op) {
        case "+": left = typeof left === "string" || typeof right === "string" ? String(left) + String(right) : numeric(left, right, op); break;
        case "-": case "*": case "/": case "%": left = numeric(left, right, op); break;
        case "==": left = left === right; break;
        case "!=": left = left !== right; break;
        case "<": left = comparable(left, right, op); break;
        case "<=": left = comparable(left, right, op, true); break;
        case ">": left = comparable(left, right, op, false, true); break;
        case ">=": left = comparable(left, right, op, true, true); break;
        case "&&": left = Boolean(left) && Boolean(right); break;
        case "||": left = Boolean(left) || Boolean(right); break;
      }
    }
    return left;
  }
  const result = parse(0);
  if (peek().kind !== "eof") throw new Error(`Unexpected token "${peek().value}".`);
  return result;
}
function numeric(a: Value, b: Value, op: string): number {
  if (typeof a !== "number" || typeof b !== "number") throw new Error(`Operator ${op} expects numeric values.`);
  if ((op === "/" || op === "%") && b === 0) throw new Error("Division by zero.");
  switch (op) { case "+": return a + b; case "-": return a - b; case "*": return a * b; case "/": return a / b; default: return a % b; }
}
function comparable(a: Value, b: Value, op: string, inclusive = false, greater = false): boolean {
  if (typeof a !== typeof b || (typeof a !== "number" && typeof a !== "string")) throw new Error(`Operator ${op} expects matching numbers or strings.`);
  if (typeof a === "number" && typeof b === "number") {
    if (greater) return inclusive ? a >= b : a > b;
    return inclusive ? a <= b : a < b;
  }
  if (typeof a === "string" && typeof b === "string") {
    if (greater) return inclusive ? a >= b : a > b;
    return inclusive ? a <= b : a < b;
  }
  throw new Error(`Operator ${op} expects matching numbers or strings.`);
}

/** Executes nested blocks in a bounded, sandboxed interpreter. */
export function runProgram(compilation: Compilation, stdin: string, blocks?: Block[]): RunResult {
  if (compilation.errors.length) return { output: "", error: compilation.errors.join("\n") };
  if (!blocks) return { output: "", error: "No block model was provided to the runtime." };
  const variables = new Map<string, Value>();
  const inputLines = stdin.split(/\r?\n/); let inputIndex = 0; let steps = 0;
  const output: string[] = [];
  function execute(items: Block[]) {
    for (const block of items) {
      if (++steps > 100000) throw new Error("Execution limit reached (100,000 blocks).");
      switch (block.kind) {
        case "print": output.push(String(block.valueBlock ? evaluateBlockValue(block.valueBlock, variables) : block.value)); break;
        case "let": {
          const name = block.name?.trim() ?? "";
          if (!identifier.test(name) || reserved.has(name)) throw new Error("Invalid variable name \"" + name + "\".");
          variables.set(name, block.valueBlock ? evaluateBlockValue(block.valueBlock, variables) : literalForRuntime(block)); break;
        }
        case "input": {
          const name = block.name?.trim() ?? "";
          if (!identifier.test(name) || reserved.has(name)) throw new Error("Invalid input variable name \"" + name + "\".");
          if (inputIndex >= inputLines.length || (inputIndex === inputLines.length - 1 && inputLines[inputIndex] === "")) throw new Error("Input exhausted. Add a line in the STDIN panel.");
          variables.set(name, inputLines[inputIndex++]!); break;
        }
        case "get": {
          const name = block.value.trim();
          if (!variables.has(name)) throw new Error(`Unknown variable "${name}".`);
          output.push(String(variables.get(name)));
          break;
        }
        case "add": output.push(String(evaluateBlockValue(block, variables))); break;
        case "true": output.push("true"); break;
        case "false": output.push("false"); break;
        case "compare": output.push(String(evaluateBlockValue(block, variables))); break;
        case "if": {
          if (Boolean(block.conditionBlock ? evaluateBlockValue(block.conditionBlock, variables) : false)) execute(block.children ?? []);
          else {
            let handled = false;
            for (const branch of block.elseIf ?? []) if (Boolean(evaluate(branch.condition || "false", variables))) { execute(branch.children); handled = true; break; }
            if (!handled && block.elseChildren) execute(block.elseChildren);
          }
          break;
        }
        case "repeat": {
          const count = block.valueBlock ? evaluateBlockValue(block.valueBlock, variables) : evaluate(block.value || "1", variables);
          if (typeof count !== "number" || !Number.isFinite(count)) throw new Error("Repeat count must be a finite number.");
          for (let i = 0; i < Math.max(0, Math.min(10000, Math.floor(count))); i++) execute(block.children ?? []);
          break;
        }
      }
    }
  }
  try { execute(blocks); return { output: output.join("\n") }; }
  catch (error) { return { output: output.join("\n"), error: error instanceof Error ? error.message : String(error) }; }
}

export function compileAssembly(blocks: Block[]): Compilation {
  const errors: string[] = [];
  const names = new Map<string, ValueType>();
  const data: string[] = [];
  const code: string[] = [];
  let labelIndex = 0;
  const label = (prefix: string) => ".L" + prefix + "_" + labelIndex++;
  const str = (value: string) => {
    const id = label("str");
    const bytes = Array.from(new TextEncoder().encode(value)).concat(0);
    data.push(id + ": .byte " + bytes.join(", "));
    return id;
  };
  const fmtInt = str("%lld\n");
  const fmtString = str("%s\n");
  const fmtScanInt = str("%lld");
  const fmtScanString = str("%4095s");
  const variableLabel = (name: string) => ".Lvar_" + name;
  const bufferLabel = (name: string) => ".Lbuf_" + name;
  function scan(items: Block[]) {
    for (const b of items) {
      if (b.kind === "let" || b.kind === "input") {
        const name = b.name?.trim() ?? "";
        if (!identifier.test(name) || reserved.has(name)) errors.push("Invalid variable name \"" + name + "\".");
        else names.set(name, selectedLiteralType(b));
      }
      if (b.conditionBlock) scan([b.conditionBlock]);
      if (b.valueBlock) scan([b.valueBlock]);
      if (b.rightBlock) scan([b.rightBlock]);
      scan(b.children ?? []);
      for (const branch of b.elseIf ?? []) scan(branch.children);
      if (b.elseChildren) scan(b.elseChildren);
    }
  }
  scan(blocks);
  for (const [name, type] of names) {
    data.push(variableLabel(name) + ": .quad 0");
    if (type === "string") data.push(bufferLabel(name) + ": .zero 4096");
  }
  const inferRawType = (raw: string): ValueType => {
    const value = raw.trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) return "string";
    if (value === "true" || value === "false") return "boolean";
    if (identifier.test(value)) return names.get(value) ?? "number";
    return "number";
  };
  function emitRaw(raw: string) {
    const value = raw.trim();
    if (!value) { code.push("  xor eax, eax"); return; }
    let tokens: Token[];
    try { tokens = tokenize(value).filter(token => token.kind !== "eof"); }
    catch (error) { errors.push(error instanceof Error ? error.message : String(error)); code.push("  xor eax, eax"); return; }
    if (tokens.length === 2 && tokens[0]!.kind === "operator" && (tokens[0]!.value === "-" || tokens[0]!.value === "+") && tokens[1]!.kind === "number") {
      const number = Number(tokens[1]!.value) * (tokens[0]!.value === "-" ? -1 : 1);
      if (!Number.isSafeInteger(number)) errors.push("Assembly backend currently requires whole-number literals: " + value);
      code.push("  mov rax, " + (Number.isSafeInteger(number) ? String(number) : "0"));
      return;
    }
    if (tokens.length === 1) {
      const token = tokens[0]!;
      if (token.kind === "number") {
        const number = Number(token.value);
        if (!Number.isSafeInteger(number)) errors.push("Assembly backend currently requires whole-number literals: " + value);
        code.push("  mov rax, " + (Number.isSafeInteger(number) ? String(number) : "0"));
      } else if (token.kind === "string") {
        code.push("  lea rax, [rip+" + str(token.value) + "]");
      } else if (token.kind === "identifier") {
        if (token.value === "true") code.push("  mov rax, 1");
        else if (token.value === "false") code.push("  xor eax, eax");
        else if (names.has(token.value)) code.push("  mov rax, QWORD PTR [rip+" + variableLabel(token.value) + "]");
        else { errors.push("Unknown variable \"" + token.value + "\"."); code.push("  xor eax, eax"); }
      }
      return;
    }
    errors.push("Use a Calculate block for arithmetic instead of typing an expression: " + value);
    code.push("  xor eax, eax");
  }
  function emitValue(block: Block): ValueType {
    if (block.kind === "true") { code.push("  mov rax, 1"); return "boolean"; }
    if (block.kind === "false") { code.push("  xor eax, eax"); return "boolean"; }
    if (block.kind === "get") {
      const name = block.value.trim();
      if (!names.has(name)) { errors.push("Unknown variable \"" + name + "\"."); code.push("  xor eax, eax"); return "number"; }
      code.push("  mov rax, QWORD PTR [rip+" + variableLabel(name) + "]");
      return names.get(name)!;
    }
    if (block.kind === "add") {
      const leftType = block.valueBlock ? emitValue(block.valueBlock) : inferRawType(block.value);
      if (!block.valueBlock) emitRaw(block.value || "0");
      code.push("  push rax");
      const rightType = block.rightBlock ? emitValue(block.rightBlock) : inferRawType(block.right ?? "1");
      if (!block.rightBlock) emitRaw(block.right || "1");
      code.push("  mov rcx, rax", "  pop rax");
      switch (block.operator ?? "+") {
        case "+": code.push("  add rax, rcx"); break;
        case "-": code.push("  sub rax, rcx"); break;
        case "*": code.push("  imul rax, rcx"); break;
        case "/": code.push("  cqo", "  idiv rcx"); break;
      }
      if (leftType === "string" || rightType === "string") errors.push("Calculate only supports numeric values.");
      return "number";
    }
    if (block.kind === "compare") {
      const leftType = block.valueBlock ? emitValue(block.valueBlock) : inferRawType(block.value);
      if (!block.valueBlock) emitRaw(block.value || "0");
      code.push("  push rax");
      const rightType = block.rightBlock ? emitValue(block.rightBlock) : inferRawType(block.right ?? "0");
      if (!block.rightBlock) emitRaw(block.right || "0");
      if (leftType === "string" || rightType === "string") {
        code.push("  mov rdx, rax", "  pop rcx", "  sub rsp, 32", "  call strcmp", "  add rsp, 32", "  cmp eax, 0");
      } else {
        code.push("  mov rcx, rax", "  pop rax", "  cmp rax, rcx");
      }
      code.push(block.comparisonOperator === ">=" ? "  setge al" : block.comparisonOperator === "<=" ? "  setle al" : "  sete al", "  movzx rax, al");
      return "boolean";
    }
    errors.push("Block " + block.kind + " cannot be inserted into a value.");
    code.push("  xor eax, eax");
    return "number";
  }
  function emitPrint(block: Block) {
    let type: ValueType;
    if (block.valueBlock) type = emitValue(block.valueBlock);
    else {
      code.push("  lea rdx, [rip+" + str(block.value) + "]");
      code.push("  lea rcx, [rip+" + fmtString + "]", "  sub rsp, 32", "  call printf", "  add rsp, 32");
      return;
    }
    code.push("  mov rdx, rax", "  lea rcx, [rip+" + (type === "string" ? fmtString : fmtInt) + "]", "  sub rsp, 32", "  call printf", "  add rsp, 32");
  }
  function emit(items: Block[]) {
    for (const block of items) {
      try {
        switch (block.kind) {
          case "print": emitPrint(block); break;
          case "let": {
            const name = block.name?.trim() ?? "";
            if (!names.has(name)) break;
            if (block.valueBlock) {
              const valueType = emitValue(block.valueBlock);
              if (names.get(name) === "string" && valueType !== "string") errors.push("Variable \"" + name + "\" expects a string value.");
            } else if (names.get(name) === "string") code.push("  lea rax, [rip+" + str(block.value) + "]");
            else if (names.get(name) === "boolean") code.push("  mov rax, " + (block.value.trim() === "true" ? "1" : "0"));
            else {
              const number = Number(block.value);
              if (!Number.isSafeInteger(number)) errors.push("Variable \"" + name + "\" needs a whole-number literal for assembly output.");
              code.push("  mov rax, " + (Number.isSafeInteger(number) ? String(number) : "0"));
            }
            code.push("  mov QWORD PTR [rip+" + variableLabel(name) + "], rax");
            break;
          }
          case "input": {
            const name = block.name?.trim() ?? "";
            if (!names.has(name)) break;
            if (names.get(name) === "string") {
              code.push("  lea rcx, [rip+" + fmtScanString + "]", "  lea rdx, [rip+" + bufferLabel(name) + "]", "  sub rsp, 32", "  call scanf", "  add rsp, 32", "  lea rax, [rip+" + bufferLabel(name) + "]", "  mov QWORD PTR [rip+" + variableLabel(name) + "], rax");
            } else {
              code.push("  lea rcx, [rip+" + fmtScanInt + "]", "  lea rdx, [rip+" + variableLabel(name) + "]", "  sub rsp, 32", "  call scanf", "  add rsp, 32");
            }
            break;
          }
          case "get": case "add": case "compare": case "true": case "false": break;
          case "if": {
            const elseLabel = label("else"), endLabel = label("endif");
            if (block.conditionBlock) emitValue(block.conditionBlock); else code.push("  xor eax, eax");
            code.push("  test rax, rax", "  jz " + elseLabel);
            emit(block.children ?? []);
            code.push("  jmp " + endLabel, elseLabel + ":");
            for (const branch of block.elseIf ?? []) {
              const next = label("elseif_next");
              emitRaw(branch.condition || "false");
              code.push("  test rax, rax", "  jz " + next);
              emit(branch.children);
              code.push("  jmp " + endLabel, next + ":");
            }
            if (block.elseChildren) emit(block.elseChildren);
            code.push(endLabel + ":");
            break;
          }
          case "repeat": {
            const start = label("loop"), end = label("endloop"), counter = label("counter");
            data.push(counter + ": .quad 0");
            if (block.valueBlock) emitValue(block.valueBlock); else emitRaw(block.value || "1");
            code.push("  mov QWORD PTR [rip+" + counter + "], rax", start + ":", "  cmp QWORD PTR [rip+" + counter + "], 0", "  jle " + end, "  cmp QWORD PTR [rip+" + counter + "], 10000", "  jg " + end);
            emit(block.children ?? []);
            code.push("  sub QWORD PTR [rip+" + counter + "], 1", "  jmp " + start, end + ":");
            break;
          }
        }
      } catch (error) { errors.push(error instanceof Error ? error.message : String(error)); }
    }
  }
  emit(blocks);
  const assembly = [
    ".intel_syntax noprefix",
    ".text",
    ".globl main",
    ".def main; .scl 2; .type 32; .endef",
    ".seh_proc main",
    "main:",
    "  push rbp",
    "  .seh_pushreg rbp",
    "  mov rbp, rsp",
    "  .seh_setframe rbp, 0",
    "  sub rsp, 32",
    "  .seh_stackalloc 32",
    "  .seh_endprologue",
    ...code,
    "  xor eax, eax",
    "  add rsp, 32",
    "  pop rbp",
    "  ret",
    ".seh_endproc",
    ".data",
    ...data,
  ];
  return { code: assembly.join("\n") + "\n", errors };
}

export function compileC(blocks: Block[]): Compilation {
  const errors: string[] = [];
  const names = new Map<string, ValueType>();
  function scan(items: Block[]) {
    for (const b of items) {
      if (b.kind === "let" || b.kind === "input") {
        const name = b.name?.trim() ?? "";
        if (!identifier.test(name) || reserved.has(name)) errors.push("Invalid variable name \"" + name + "\".");
        else names.set(name, selectedLiteralType(b));
      }
      if (b.conditionBlock) scan([b.conditionBlock]);
      scan(b.children ?? []);
      for (const branch of b.elseIf ?? []) scan(branch.children);
      if (b.elseChildren) scan(b.elseChildren);
    }
  }
  scan(blocks);
  const expr = (s: string) => {
    if (!/^[\w\s"'().,+\-*/%<>=!&|\\]+$/.test(s)) throw new Error("Expression contains unsupported characters.");
    return s.replace(/\btrue\b/g, "1").replace(/\bfalse\b/g, "0");
  };
  const cCompare = (left: string, operator: "==" | ">=" | "<=", right: string) => {
    const isString = (value: string) => {
      const trimmed = value.trim();
      return (trimmed.startsWith('"') && trimmed.endsWith('"')) || names.get(trimmed) === "string";
    };
    if (isString(left) || isString(right)) return "strcmp(" + expr(left) + ", " + expr(right) + ") " + operator + " 0";
    return "(" + expr(left) + ") " + operator + " (" + expr(right) + ")";
  };
  const cCondition = (block: Block) => block.kind === "compare"
    ? cCompare(block.value || "0", block.comparisonOperator ?? "==", block.right || "0")
    : expr(conditionExpression(block));
  const lines = ["#include <stdio.h>", "#include <stdlib.h>", "#include <string.h>", "int main(void) {"];
  for (const [name,type] of names) lines.push("  " + (type === "string" ? "const char *" : "double") + " " + name + " = " + (type === "string" ? '""' : "0") + ";");
  let temp = 0;
  function emit(items: Block[], depth: number) {
    const pad = "  ".repeat(depth);
    for (const b of items) try {
      if (b.kind === "print") {
        lines.push(pad + "printf(\"%s\\n\", " + JSON.stringify(b.value) + ");");
      } else if (b.kind === "get") {
        const name = b.value.trim();
        if (!identifier.test(name) || !names.has(name)) errors.push("Unknown variable \"" + name + "\".");
        else lines.push(pad + "printf(" + (names.get(name) === "string" ? '"%s\\\\n", ' : '"%.15g\\\\n", ') + name + ");");
      } else if (b.kind === "let") lines.push(pad + (b.name?.trim() ?? "value") + " = " + literalForC(b) + ";");
      else if (b.kind === "input") {
        const name = b.name?.trim() ?? "value";
        if (names.get(name) === "string") lines.push(`${pad}{ static char buf_${name}[4096]; if (fgets(buf_${name}, sizeof(buf_${name}), stdin)) { buf_${name}[strcspn(buf_${name}, "\\n")] = 0; ${name} = buf_${name}; } }`);
        else lines.push(`${pad}scanf("%lf", &${name});`);
      } else if (b.kind === "add") lines.push(`${pad}printf("%.15g\\n", (${expr(b.value || "0")}) ${b.operator ?? "+"} (${expr(b.right || "1")}));`);
      else if (b.kind === "true") lines.push(pad + "printf(\"%s\\n\", \"true\");");
      else if (b.kind === "false") lines.push(pad + "printf(\"%s\\n\", \"false\");");
      else if (b.kind === "compare") lines.push(pad + "printf(\"%d\\n\", " + cCompare(b.value || "0", b.comparisonOperator ?? "==", b.right || "0") + ");");
      else if (b.kind === "if") {
        lines.push(pad + "if (" + (b.conditionBlock ? cCondition(b.conditionBlock) : "0") + ") {"); emit(b.children ?? [],depth+1); lines.push(pad+"}");
        for (const br of b.elseIf ?? []) { lines.push(pad+"else if ("+expr(br.condition||"0")+") {");emit(br.children,depth+1);lines.push(pad+"}"); }
        if (b.elseChildren) {lines.push(pad+"else {");emit(b.elseChildren,depth+1);lines.push(pad+"}");}
      } else if (b.kind === "repeat") {
        const i = "blorrl_i_" + temp++;
        lines.push(pad + "for (int " + i + " = 0; " + i + " < (int)(" + expr(b.value || "1") + ") && " + i + " < 10000; ++" + i + ") {");
        emit(b.children ?? [],depth+1); lines.push(pad+"}");
      }
    } catch(error) { errors.push(error instanceof Error ? error.message : String(error)); }
  }
  emit(blocks,1); lines.push("  return 0;","}");
  return {code:lines.join("\n"),errors};
}
