export type BlockKind = "print" | "let" | "input" | "get" | "if" | "repeat" | "add";
export type ValueType = "number" | "string" | "boolean";
export type Branch = { id: string; condition: string; children: Block[] };
export type Block = {
  id: string; kind: BlockKind; value: string; name?: string; right?: string;
  operator?: "+" | "-" | "*" | "/"; types?: ValueType[]; children?: Block[];
  elseIf?: Branch[]; elseChildren?: Block[]; elseId?: string;
};
export type Compilation = { code: string; errors: string[] };
export type RunResult = { output: string; error?: string };
const identifier = /^[A-Za-z_][A-Za-z0-9_]*$/;
const reserved = new Set(["print", "let", "input", "get", "if", "repeat", "true", "false", "else"]);

export function compile(blocks: Block[]): Compilation {
  const errors: string[] = [];
  const lines: string[] = ["// Generated by Blorrl Studio", ""];
  function emit(items: Block[], depth: number) {
    const pad = "  ".repeat(depth);
    for (const [index, block] of items.entries()) {
      const line = index + 1;
      switch (block.kind) {
        case "print": lines.push(pad + "print " + JSON.stringify(block.value) + ";"); break;
        case "let": {
          const name = block.name?.trim() ?? "";
          if (!identifier.test(name) || reserved.has(name)) errors.push("Block " + line + ": invalid variable name \"" + name + "\".");
          else lines.push(pad + "let " + name + " = " + (block.value || "0") + ";");
          break;
        }
        case "input": {
          const name = block.name?.trim() ?? "";
          if (!identifier.test(name) || reserved.has(name)) errors.push("Block " + line + ": invalid input variable name \"" + name + "\".");
          else lines.push(pad + "let " + name + " = input();");
          break;
        }
        case "get": lines.push(pad + "print " + (block.value || "value") + ";"); break;
        case "if":
          lines.push(pad + "if (" + (block.value || "false") + ") {");
          emit(block.children ?? [], depth + 1); lines.push(pad + "}");
          for (const branch of block.elseIf ?? []) {
            lines.push(pad + "else if (" + (branch.condition || "false") + ") {");
            emit(branch.children, depth + 1); lines.push(pad + "}");
          }
          if (block.elseChildren) { lines.push(pad + "else {"); emit(block.elseChildren, depth + 1); lines.push(pad + "}"); }
          break;
        case "repeat":
          lines.push(pad + "repeat (" + (block.value || "1") + ") {");
          emit(block.children ?? [], depth + 1); lines.push(pad + "}"); break;
        case "add": lines.push(pad + "print (" + (block.value || "0") + ") " + (block.operator ?? "+") + " (" + (block.right || "1") + ");"); break;
      }
    }
  }
  emit(blocks, 0);
  return { code: lines.join("\n"), errors };
}

type Token = { kind: "number" | "string" | "identifier" | "operator" | "eof"; value: string };
function tokenize(source: string): Token[] {
  const tokens: Token[] = [];
  let i = 0;
  while (i < source.length) {
    const ch = source[i]!;
    if (/\s/.test(ch)) { i++; continue; }
    if (ch === '"' || ch === "'") {
      const quote = ch; let value = ""; i++;
      while (i < source.length && source[i] !== quote) {
        if (source[i] === "\\" && i + 1 < source.length) {
          i++; const escaped = source[i]!;
          value += escaped === "n" ? "\n" : escaped === "t" ? "\t" : escaped;
        } else value += source[i];
        i++;
      }
      if (source[i] !== quote) throw new Error("Unterminated string literal.");
      i++; tokens.push({ kind: "string", value }); continue;
    }
    const number = source.slice(i).match(/^(?:\d+\.\d+|\d+|\.\d+)/);
    if (number) { tokens.push({ kind: "number", value: number[0] }); i += number[0].length; continue; }
    const name = source.slice(i).match(/^[A-Za-z_][A-Za-z0-9_]*/);
    if (name) { tokens.push({ kind: "identifier", value: name[0] }); i += name[0].length; continue; }
    const operator = ["==", "!=", "<=", ">=", "&&", "||", "+", "-", "*", "/", "%", "<", ">", "!", "(", ")"].find(op => source.startsWith(op, i));
    if (operator) { tokens.push({ kind: "operator", value: operator }); i += operator.length; continue; }
    throw new Error(`Unexpected character "${ch}" in expression.`);
  }
  tokens.push({ kind: "eof", value: "" });
  return tokens;
}

type Value = number | string | boolean;
const precedence: Record<string, number> = { "||": 1, "&&": 2, "==": 3, "!=": 3, "<": 4, "<=": 4, ">": 4, ">=": 4, "+": 5, "-": 5, "*": 6, "/": 6, "%": 6 };

function evaluate(expression: string, variables: Map<string, Value>): Value {
  const tokens = tokenize(expression);
  let position = 0;
  const peek = () => tokens[position]!;
  const take = () => tokens[position++]!;
  function primary(): Value {
    const token = take();
    if (token.kind === "number") return Number(token.value);
    if (token.kind === "string") return token.value;
    if (token.kind === "identifier") {
      if (token.value === "true") return true;
      if (token.value === "false") return false;
      if (!variables.has(token.value)) throw new Error(`Unknown variable "${token.value}".`);
      return variables.get(token.value)!;
    }
    if (token.value === "(") {
      const result = parse(0);
      if (take().value !== ")") throw new Error('Expected ")".');
      return result;
    }
    if (token.value === "!" || token.value === "-" || token.value === "+") {
      const value = primary();
      if (token.value === "!") return !value;
      if (typeof value !== "number") throw new Error(`Unary ${token.value} expects a number.`);
      return token.value === "-" ? -value : value;
    }
    throw new Error(`Expected a value, got "${token.value || "end of expression"}".`);
  }
  function parse(minPrecedence: number): Value {
    let left = primary();
    while (peek().kind === "operator" && (precedence[peek().value] ?? -1) >= minPrecedence) {
      const op = take().value;
      const right = parse((precedence[op] ?? 0) + 1);
      switch (op) {
        case "+": left = typeof left === "string" || typeof right === "string" ? String(left) + String(right) : numeric(left, right, op); break;
        case "-": case "*": case "/": case "%": left = numeric(left, right, op); break;
        case "==": left = left === right; break;
        case "!=": left = left !== right; break;
        case "<": left = comparable(left, right, op); break;
        case "<=": left = comparable(left, right, op, true); break;
        case ">": left = comparable(left, right, op, false, true); break;
        case ">=": left = comparable(left, right, op, true, true); break;
        case "&&": left = Boolean(left) && Boolean(right); break;
        case "||": left = Boolean(left) || Boolean(right); break;
      }
    }
    return left;
  }
  const result = parse(0);
  if (peek().kind !== "eof") throw new Error(`Unexpected token "${peek().value}".`);
  return result;
}
function numeric(a: Value, b: Value, op: string): number {
  if (typeof a !== "number" || typeof b !== "number") throw new Error(`Operator ${op} expects numeric values.`);
  if ((op === "/" || op === "%") && b === 0) throw new Error("Division by zero.");
  switch (op) { case "+": return a + b; case "-": return a - b; case "*": return a * b; case "/": return a / b; default: return a % b; }
}
function comparable(a: Value, b: Value, op: string, inclusive = false, greater = false): boolean {
  if (typeof a !== typeof b || (typeof a !== "number" && typeof a !== "string")) throw new Error(`Operator ${op} expects matching numbers or strings.`);
  if (typeof a === "number" && typeof b === "number") {
    if (greater) return inclusive ? a >= b : a > b;
    return inclusive ? a <= b : a < b;
  }
  if (typeof a === "string" && typeof b === "string") {
    if (greater) return inclusive ? a >= b : a > b;
    return inclusive ? a <= b : a < b;
  }
  throw new Error(`Operator ${op} expects matching numbers or strings.`);
}

/** Executes nested blocks in a bounded, sandboxed interpreter. */
export function runProgram(compilation: Compilation, stdin: string, blocks?: Block[]): RunResult {
  if (compilation.errors.length) return { output: "", error: compilation.errors.join("\n") };
  if (!blocks) return { output: "", error: "No block model was provided to the runtime." };
  const variables = new Map<string, Value>();
  const inputLines = stdin.split(/\r?\n/); let inputIndex = 0; let steps = 0;
  const output: string[] = [];
  function execute(items: Block[]) {
    for (const block of items) {
      if (++steps > 100000) throw new Error("Execution limit reached (100,000 blocks).");
      switch (block.kind) {
        case "print": output.push(block.value); break;
        case "let": {
          const name = block.name?.trim() ?? "";
          if (!identifier.test(name) || reserved.has(name)) throw new Error("Invalid variable name \"" + name + "\".");
          variables.set(name, evaluate(block.value || "0", variables)); break;
        }
        case "input": {
          const name = block.name?.trim() ?? "";
          if (!identifier.test(name) || reserved.has(name)) throw new Error("Invalid input variable name \"" + name + "\".");
          if (inputIndex >= inputLines.length || (inputIndex === inputLines.length - 1 && inputLines[inputIndex] === "")) throw new Error("Input exhausted. Add a line in the STDIN panel.");
          variables.set(name, inputLines[inputIndex++]!); break;
        }
        case "get": {
          const name = block.value.trim();
          if (!variables.has(name)) throw new Error(`Unknown variable "${name}".`);
          output.push(String(variables.get(name)));
          break;
        }
        case "add": output.push(String(evaluate("(" + (block.value || "0") + ") " + (block.operator ?? "+") + " (" + (block.right || "1") + ")", variables))); break;
        case "if": {
          if (Boolean(evaluate(block.value || "false", variables))) execute(block.children ?? []);
          else {
            let handled = false;
            for (const branch of block.elseIf ?? []) if (Boolean(evaluate(branch.condition || "false", variables))) { execute(branch.children); handled = true; break; }
            if (!handled && block.elseChildren) execute(block.elseChildren);
          }
          break;
        }
        case "repeat": {
          const count = evaluate(block.value || "1", variables);
          if (typeof count !== "number" || !Number.isFinite(count)) throw new Error("Repeat count must be a finite number.");
          for (let i = 0; i < Math.max(0, Math.min(10000, Math.floor(count))); i++) execute(block.children ?? []);
          break;
        }
      }
    }
  }
  try { execute(blocks); return { output: output.join("\n") }; }
  catch (error) { return { output: output.join("\n"), error: error instanceof Error ? error.message : String(error) }; }
}

export function compileC(blocks: Block[]): Compilation {
  const errors: string[] = [];
  const names = new Map<string, ValueType>();
  function scan(items: Block[]) {
    for (const b of items) {
      if (b.kind === "let" || b.kind === "input") {
        const name = b.name?.trim() ?? "";
        if (!identifier.test(name) || reserved.has(name)) errors.push("Invalid variable name \"" + name + "\".");
        else names.set(name, b.types?.includes("string") && !b.types.includes("number") ? "string" : b.types?.includes("boolean") && !b.types.includes("number") ? "boolean" : "number");
      }
      scan(b.children ?? []);
      for (const branch of b.elseIf ?? []) scan(branch.children);
      if (b.elseChildren) scan(b.elseChildren);
    }
  }
  scan(blocks);
  const expr = (s: string) => {
    if (!/^[\w\s"'().,+\-*/%<>=!&|\\]+$/.test(s)) throw new Error("Expression contains unsupported characters.");
    return s.replace(/\btrue\b/g, "1").replace(/\bfalse\b/g, "0");
  };
  const lines = ["#include <stdio.h>", "#include <stdlib.h>", "#include <string.h>", "int main(void) {"];
  for (const [name,type] of names) lines.push("  " + (type === "string" ? "const char *" : "double") + " " + name + " = " + (type === "string" ? '""' : "0") + ";");
  let temp = 0;
  function emit(items: Block[], depth: number) {
    const pad = "  ".repeat(depth);
    for (const b of items) try {
      if (b.kind === "print") {
        lines.push(pad + "printf(\"%s\\n\", " + JSON.stringify(b.value) + ");");
      } else if (b.kind === "get") {
        const name = b.value.trim();
        if (!identifier.test(name) || !names.has(name)) errors.push("Unknown variable \"" + name + "\".");
        else lines.push(pad + "printf(" + (names.get(name) === "string" ? '"%s\\\\n", ' : '"%.15g\\\\n", ') + name + ");");
      } else if (b.kind === "let") lines.push(pad + (b.name?.trim() ?? "value") + " = " + expr(b.value || "0") + ";");
      else if (b.kind === "input") {
        const name = b.name?.trim() ?? "value";
        if (names.get(name) === "string") lines.push(`${pad}{ static char buf_${name}[4096]; if (fgets(buf_${name}, sizeof(buf_${name}), stdin)) { buf_${name}[strcspn(buf_${name}, "\\n")] = 0; ${name} = buf_${name}; } }`);
        else lines.push(`${pad}scanf("%lf", &${name});`);
      } else if (b.kind === "add") lines.push(`${pad}printf("%.15g\\n", (${expr(b.value || "0")}) ${b.operator ?? "+"} (${expr(b.right || "1")}));`);
      else if (b.kind === "if") {
        lines.push(pad + "if (" + expr(b.value || "0") + ") {"); emit(b.children ?? [],depth+1); lines.push(pad+"}");
        for (const br of b.elseIf ?? []) { lines.push(pad+"else if ("+expr(br.condition||"0")+") {");emit(br.children,depth+1);lines.push(pad+"}"); }
        if (b.elseChildren) {lines.push(pad+"else {");emit(b.elseChildren,depth+1);lines.push(pad+"}");}
      } else if (b.kind === "repeat") {
        const i = "blorrl_i_" + temp++;
        lines.push(pad + "for (int " + i + " = 0; " + i + " < (int)(" + expr(b.value || "1") + ") && " + i + " < 10000; ++" + i + ") {");
        emit(b.children ?? [],depth+1); lines.push(pad+"}");
      }
    } catch(error) { errors.push(error instanceof Error ? error.message : String(error)); }
  }
  emit(blocks,1); lines.push("  return 0;","}");
  return {code:lines.join("\n"),errors};
}
